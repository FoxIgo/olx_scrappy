"""Identifiers shared by several domain modules."""

from __future__ import annotations

import re
from dataclasses import dataclass

from scrappy.domain.shared.errors import InvalidValueError

_SLUG = re.compile(r"^[a-z0-9][a-z0-9_-]{0,63}$")


def validate_slug(value: str, kind: str) -> str:
    """Return ``value`` if it is a lowercase slug (``[a-z0-9][a-z0-9_-]*``, max 64 chars)."""
    if not _SLUG.fullmatch(value):
        raise InvalidValueError(f"invalid {kind} {value!r}: expected a lowercase slug")
    return value


@dataclass(frozen=True, slots=True)
class SourceId:
    """Site recipe identifier, e.g. ``olx_pl`` (ADR 0004)."""

    value: str

    def __post_init__(self) -> None:
        validate_slug(self.value, "source id")

    def __str__(self) -> str:
        return self.value


@dataclass(frozen=True, slots=True)
class RunId:
    """Identity of a ``ScrapeRun`` (opaque string generated by the application)."""

    value: str

    def __post_init__(self) -> None:
        if not self.value or self.value != self.value.strip() or ":" in self.value:
            raise InvalidValueError("RunId must be a non-empty trimmed string without ':'")

    def __str__(self) -> str:
        return self.value
