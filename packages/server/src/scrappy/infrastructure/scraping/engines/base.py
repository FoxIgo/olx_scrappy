"""Engine-internal abstractions for fetching pages (ADR 0004 sections 2, 8).

Self-contained on purpose: engines must not import ``scrappy.application`` or
``scrappy.domain``. ``GONE`` (removed or sold offer) is deliberately absent from
:class:`EngineFetchOutcome`: only a site recipe can tell what a removed page looks
like, so the recipe/domain maps pages to GONE on top of the generic outcome.
"""

from __future__ import annotations

import enum
from collections.abc import Callable, Mapping
from dataclasses import dataclass, field
from types import TracebackType
from typing import Protocol, Self, runtime_checkable


@dataclass(frozen=True)
class FetchRequest:
    """What to fetch. ``render_js`` and ``wait_for`` are hints for browser engines."""

    url: str
    method: str = "GET"
    params: Mapping[str, str] = field(default_factory=dict)
    headers: Mapping[str, str] = field(default_factory=dict)
    render_js: bool = False
    wait_for: str | None = None  # CSS selector hint for browser engines
    timeout: float = 30.0  # seconds


@dataclass(frozen=True)
class RawPage:
    """Result of a fetch for any HTTP status. Header names are lower-cased."""

    url: str
    final_url: str
    status: int
    headers: Mapping[str, str]
    content_type: str
    body: str
    elapsed: float  # seconds
    engine: str
    archive_ref: str | None = None  # set by ArchivingFetcher


class EngineFetchOutcome(enum.Enum):
    OK = "ok"  # real content (or an HTTP status the recipe should interpret)
    BLOCKED = "blocked"  # 403/429, captcha or challenge page: retry later / escalate
    NOT_FOUND = "not_found"  # 404/410: a valid answer, not an error
    TRANSIENT = "transient"  # 5xx: retry


class FetchError(Exception):
    """Base class for engine errors."""


class FetchTransportError(FetchError):
    """Network-level failure: DNS, connect, TLS, timeout, ..."""


class FetchBlocked(FetchError):
    """Raised by callers (e.g. recipes) that cannot proceed with a blocked page."""

    def __init__(self, page: RawPage, message: str | None = None) -> None:
        super().__init__(message or f"blocked: HTTP {page.status} from {page.final_url}")
        self.page = page


class FetchEngineUnavailable(FetchError):
    """An engine needs an optional dependency that is not installed."""


Classifier = Callable[[RawPage], EngineFetchOutcome]

_STRONG_MARKERS = (
    "generated by cloudfront",
    "the request could not be satisfied",
    "cf-chl",
    "just a moment...",
    "attention required! | cloudflare",
    "checking your browser before accessing",
)
# A 200 page bigger than this is real content that merely mentions a marker.
_MAX_CHALLENGE_BODY = 50_000


def has_challenge_marker(page: RawPage) -> bool:
    body = page.body.lower()
    return any(marker in body for marker in _STRONG_MARKERS)


def classify_generic(page: RawPage) -> EngineFetchOutcome:
    """Status codes and known challenge markers only; recipes add site rules.

    Other 4xx statuses (400, 401, ...) are OK here: the recipe decides what they mean.
    """
    status = page.status
    if status in (403, 429):
        return EngineFetchOutcome.BLOCKED
    if status in (404, 410):
        return EngineFetchOutcome.NOT_FOUND
    if status >= 500:
        # Cloudflare/CloudFront challenges are sometimes served as 503.
        if has_challenge_marker(page):
            return EngineFetchOutcome.BLOCKED
        return EngineFetchOutcome.TRANSIENT
    if len(page.body) <= _MAX_CHALLENGE_BODY and has_challenge_marker(page):
        return EngineFetchOutcome.BLOCKED
    return EngineFetchOutcome.OK


@runtime_checkable
class PageFetcher(Protocol):
    async def fetch(self, req: FetchRequest) -> RawPage: ...

    async def aclose(self) -> None: ...


class FetcherBase:
    """Optional convenience base: async context manager support and a no-op aclose."""

    async def aclose(self) -> None:  # pragma: no cover - trivial
        return None

    async def __aenter__(self) -> Self:
        return self

    async def __aexit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        tb: TracebackType | None,
    ) -> None:
        await self.aclose()
