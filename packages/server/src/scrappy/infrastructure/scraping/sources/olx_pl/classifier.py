"""olx.pl specific outcome rules on top of :func:`classify_generic` (ADR 0004 section 8).

Order of rules for an API response:

1. 403/429 or a CloudFront / challenge body -> BLOCKED
2. 404 (new ``{"error": {"detail": "Ad not found."}}`` or legacy ``application/x-json``
   error body, or the HTML 404 SPA page) -> NOT_FOUND
3. 400 mentioning ``offset`` or ``limit`` -> RESULT_CAP (end of reachable results, not an error)
4. any other 4xx / 5xx -> TRANSIENT
5. 200 with an HTML body where JSON was expected -> BLOCKED (challenge / unexpected page)
6. otherwise OK

A *removed* offer (200 with ``status != active``) is decided by the source from the payload.
"""

from __future__ import annotations

import enum
import json
from dataclasses import dataclass
from datetime import timedelta

from scrappy.domain.shared import FetchOutcome
from scrappy.infrastructure.scraping.engines.base import (
    EngineFetchOutcome,
    RawPage,
    classify_generic,
)
from scrappy.infrastructure.scraping.engines.decorators import parse_retry_after

STATE_MARKER = "__PRERENDERED_STATE__"


class PageKind(enum.Enum):
    OK = "ok"
    BLOCKED = "blocked"
    NOT_FOUND = "not_found"
    TRANSIENT = "transient"
    RESULT_CAP = "result_cap"
    """400 for offset > 1000 / limit > 50: the search cannot go further."""


_OUTCOMES = {
    PageKind.OK: FetchOutcome.OK,
    PageKind.RESULT_CAP: FetchOutcome.OK,
    PageKind.BLOCKED: FetchOutcome.BLOCKED,
    PageKind.NOT_FOUND: FetchOutcome.NOT_FOUND,
    PageKind.TRANSIENT: FetchOutcome.TRANSIENT,
}


@dataclass(frozen=True, slots=True)
class Classification:
    kind: PageKind
    message: str | None = None

    @property
    def fetch_outcome(self) -> FetchOutcome:
        """Outcome for the port. RESULT_CAP is an OK end of results."""
        return _OUTCOMES[self.kind]


def retry_after_of(page: RawPage) -> timedelta | None:
    seconds = parse_retry_after(page.headers.get("retry-after"))
    return timedelta(seconds=seconds) if seconds is not None else None


def _error_text(page: RawPage) -> str:
    """Best-effort text of an API error body (new and legacy shapes)."""
    try:
        data = json.loads(page.body)
    except ValueError:
        return page.body[:200]
    error = data.get("error") if isinstance(data, dict) else None  # pyright: ignore[reportUnknownMemberType]
    if isinstance(error, dict):
        return json.dumps(error, ensure_ascii=False)
    return str(data)[:200]


def _is_cloudfront(page: RawPage) -> bool:
    return "cloudfront" in page.headers.get("server", "").lower() or (
        "generated by cloudfront" in page.body.lower()
    )


def classify_api(page: RawPage) -> Classification:
    generic = classify_generic(page)
    if generic is EngineFetchOutcome.BLOCKED:
        who = "CloudFront" if _is_cloudfront(page) else "challenge"
        return Classification(PageKind.BLOCKED, f"blocked ({who}), HTTP {page.status}")
    if generic is EngineFetchOutcome.NOT_FOUND:
        return Classification(PageKind.NOT_FOUND, f"HTTP {page.status}: {_error_text(page)}")
    if generic is EngineFetchOutcome.TRANSIENT:
        return Classification(PageKind.TRANSIENT, f"HTTP {page.status}")
    if page.status == 400:
        text = _error_text(page)
        if "offset" in text or "limit" in text:
            return Classification(PageKind.RESULT_CAP, f"HTTP 400: {text}")
        return Classification(PageKind.TRANSIENT, f"HTTP 400: {text}")
    if page.status >= 400:
        return Classification(PageKind.TRANSIENT, f"HTTP {page.status}: {_error_text(page)}")
    if page.body.lstrip().startswith("<"):
        return Classification(PageKind.BLOCKED, "HTML received where JSON was expected")
    return Classification(PageKind.OK)


def classify_html(page: RawPage) -> Classification:
    """For the embedded-state fallback: a 200 page without the state is a challenge page."""
    generic = classify_generic(page)
    if generic is EngineFetchOutcome.BLOCKED:
        return Classification(PageKind.BLOCKED, f"blocked, HTTP {page.status}")
    if generic is EngineFetchOutcome.NOT_FOUND:
        return Classification(PageKind.NOT_FOUND, f"HTTP {page.status}")
    if generic is EngineFetchOutcome.TRANSIENT or page.status >= 400:
        return Classification(PageKind.TRANSIENT, f"HTTP {page.status}")
    if STATE_MARKER not in page.body:
        return Classification(PageKind.BLOCKED, f"no {STATE_MARKER} in a 200 page")
    return Classification(PageKind.OK)
