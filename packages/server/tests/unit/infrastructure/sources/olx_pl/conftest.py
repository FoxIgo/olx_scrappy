def make_page(
    body: str | dict[str, Any],
    status: int = 200,
    *,
    url: str = "https://www.olx.pl/api/v1/offers/",
    headers: dict[str, str] | None = None,
    content_type: str = "application/json",
) -> RawPage:
    text = body if isinstance(body, str) else json.dumps(body, ensure_ascii=False)
    return RawPage(
        url=url,
        final_url=url,
        status=status,
        headers=headers or {},
        content_type=content_type,
        body=text,
        elapsed=0.01,
        engine="fake",
    )


class FakeFetcher:
    """Replays scripted RawPages / exceptions; repeats the last one."""

    def __init__(self, *results: RawPage | Exception) -> None:
        self.results = list(results)
        self.calls: list[FetchRequest] = []

    async def fetch(self, req: FetchRequest) -> RawPage:
        self.calls.append(req)
        item = self.results[min(len(self.calls) - 1, len(self.results) - 1)]
        if isinstance(item, Exception):
            raise item
        return item

    async def aclose(self) -> None:
        return None


